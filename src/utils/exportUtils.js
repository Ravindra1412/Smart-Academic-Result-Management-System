import { jsPDF } from 'jspdf';
import { avg, grade, isPass, getRank } from './helpers';
import { MAX_MARK } from './constants';
import { showToast } from './toast';

// ── CSV download helper (attached to window for legacy inline calls) ───────
window.dl = (content, name) => {
  const b = new Blob([content], {type:'text/csv'}), u = URL.createObjectURL(b);
  const a = document.createElement('a'); a.href=u; a.download=name;
  document.body.appendChild(a); a.click(); document.body.removeChild(a);
  URL.revokeObjectURL(u); showToast('📥 Downloaded!','#4d8dff');
};



// ── PDF export utilities (jsPDF) ────────────────────────────────────────────
function buildStudentPDF(stu, schoolName, academicYear, passMark, students) {
  const doc = new jsPDF();
  const a = avg(stu.marks), g = grade(a), pass = isPass(stu, passMark);
  const total = Object.values(stu.marks).reduce((s,v)=>s+v,0);
  const rank = getRank(stu, students);
  // Header
  doc.setFillColor(11,16,35); doc.rect(0,0,210,30,'F');
  doc.setTextColor(255,255,255); doc.setFontSize(15); doc.setFont('helvetica','bold');
  doc.text('EduResult Pro — Student Report Card', 105, 12, {align:'center'});
  doc.setFontSize(8); doc.setFont('helvetica','normal');
  doc.text(`${schoolName} | ${academicYear}`, 105, 20, {align:'center'});
  // Student info
  doc.setTextColor(0,0,0); doc.setFontSize(13); doc.setFont('helvetica','bold');
  doc.text(stu.name, 14, 40);
  doc.setFontSize(9); doc.setFont('helvetica','normal'); doc.setTextColor(100,100,120);
  doc.text(`Roll: ${stu.roll}  |  Class: ${stu.cls}  |  Gender: ${stu.gender}  |  Category: ${stu.cat||'General'}`, 14, 47);
  if(stu.email) doc.text(`Email: ${stu.email}  |  Phone: ${stu.phone||'N/A'}`, 14, 53);
  // Stat boxes
  const stats=[[`${a}%`,'Overall Avg'],[g,'Grade'],[pass?'PASS':'FAIL','Result'],[`#${rank}`,'Rank'],[`${total}`,'Total Marks']];
  stats.forEach(([v,l],i)=>{
    const x=14+i*38;
    doc.setFillColor(245,247,255); doc.roundedRect(x,58,36,16,2,2,'F');
    doc.setTextColor(30,140,80); doc.setFontSize(10); doc.setFont('helvetica','bold');
    doc.text(v,x+18,67,{align:'center'});
    doc.setTextColor(120,130,160); doc.setFontSize(7); doc.setFont('helvetica','normal');
    doc.text(l,x+18,72,{align:'center'});
  });
  // Table header
  let y=84;
  doc.setFillColor(30,37,64); doc.rect(14,y,182,8,'F');
  doc.setTextColor(255,255,255); doc.setFontSize(7.5); doc.setFont('helvetica','bold');
  const xs=[14,76,96,118,140,162];
  ['Subject','Max','Obtained','%','Grade','Status'].forEach((h,i)=>doc.text(h,xs[i]+2,y+5.5));
  y+=8;
  Object.keys(stu.marks).forEach((k,idx)=>{
    const m=stu.marks[k], pct=Math.round(m/MAX_MARK*100), g2=grade(pct);
    doc.setFillColor(idx%2===0?245:255,idx%2===0?247:255,255);
    doc.rect(14,y,182,8,'F');
    doc.setTextColor(30,35,60); doc.setFontSize(7.5); doc.setFont('helvetica','normal');
    [k.replace(/([A-Z])/g,' $1').trim(),MAX_MARK,m,pct+'%',g2,m>=passMark?'Pass':'Fail'].forEach((v,j)=>doc.text(String(v),xs[j]+2,y+5.5));
    y+=8;
  });
  y+=6;
  doc.setFontSize(8); doc.setTextColor(120,130,160);
  doc.text(`Generated by EduResult Pro on ${new Date().toLocaleDateString('en-IN')}`,105,y,{align:'center'});
  doc.save(`${stu.roll}_ResultCard.pdf`);
  showToast('📄 PDF downloaded!','#12c98a');
}

function exportAdminPDF(students, schoolName, academicYear, passMark) {
  const doc = new jsPDF('landscape');
  doc.setFillColor(11,16,35); doc.rect(0,0,297,22,'F');
  doc.setTextColor(255,255,255); doc.setFontSize(14); doc.setFont('helvetica','bold');
  doc.text('EduResult Pro — Class Report', 148, 10, {align:'center'});
  doc.setFontSize(8); doc.setFont('helvetica','normal');
  doc.text(`${schoolName} | ${academicYear}`, 148, 17, {align:'center'});
  let y=30;
  doc.setFillColor(30,37,64); doc.rect(10,y,277,8,'F');
  doc.setTextColor(255,255,255); doc.setFontSize(7.5); doc.setFont('helvetica','bold');
  const hdrs=['Roll','Name','Class','Maths','Sci','Eng','SSt','Hindi','CS','Total','Avg%','Grade','Status'];
  const xs=[10,28,62,76,92,106,120,134,148,163,178,193,207];
  hdrs.forEach((h,i)=>doc.text(h,xs[i]+1,y+5.5));
  y+=8;
  students.forEach((s,idx)=>{
    const mv=[s.marks.Mathematics,s.marks.Science,s.marks.English,s.marks.SocialStudies,s.marks.Hindi,s.marks.ComputerScience];
    const tot=mv.reduce((a,b)=>a+b,0), a2=Math.round(tot/6), g2=grade(a2);
    doc.setFillColor(idx%2===0?245:255,idx%2===0?247:255,255);
    doc.rect(10,y,277,8,'F');
    doc.setTextColor(30,35,60); doc.setFontSize(7.5); doc.setFont('helvetica','normal');
    [s.roll,s.name,s.cls,...mv,tot,a2+'%',g2,isPass(s,passMark)?'Pass':'Fail'].forEach((v,j)=>doc.text(String(v),xs[j]+1,y+5.5));
    y+=8;
    if(y>185){doc.addPage('landscape');y=20;}
  });
  doc.save('class_report.pdf');
  showToast('📄 Class PDF downloaded!','#12c98a');
}


export { buildStudentPDF, exportAdminPDF };
